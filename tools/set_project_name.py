#!/usr/bin/env python3
"""Project identity (name, firmware product, FWID magic, Wi-Fi prefix, NVS namespace...) in one place.

project.json in the repository root is the only source. This tool writes the two derived copies:
    firmware/include/project_identity.h   macros used by the firmware and read by firmware/tools/*.py
    firmware/web/app.js                   one line "const IDENT = ..." used by the web panel
and the lines listed in TEXT_RULES (title lines, site_name, the "<host>.local" comments), and lists
every other place where the current values still appear (docs, tests, test patterns).
Tests, file names generated by the firmware and the tools, and the panel take the values from the
derived copies, so they need no change. HISTORY files (CHANGELOG.md) keep the old values.
NOT covered: the logo and the other graphics (docs/assets/brand/, hardware/brand/) show the name
as a drawing, in the SVG <title> and in one file name; replace them by hand
(docs/en/contributing/brand.md). --check does not look at them.

Usage (from the repository root, Python standard library only):
    python -I tools/set_project_name.py --check              derived copies match project.json (exit 0/1)
    python -I tools/set_project_name.py --regen              rewrite the derived copies from project.json
    python -I tools/set_project_name.py --dry-run NEW_NAME   show new values and every place to review
    python -I tools/set_project_name.py --apply NEW_NAME     write project.json and the derived copies
Options: --set key=value (override one derived value), --root DIR (another checkout, e.g. a test copy).

COMPATIBILITY: fw_product and fwid_magic are checked by the Wi-Fi update of already installed units
(an image with other values is refused), nvs_namespace holds the saved settings (a new namespace
starts empty) and web_session_key only affects a logged-in browser tab. --apply changes them all;
use --set to keep the old ones. --apply does not touch tests, test patterns or other docs: the
--dry-run list shows what has to be reviewed by hand (REVIEW), what --apply rewrites (auto) and
what stays as history (keep). --check also fails when a TEXT_RULES line lost the current value.
"""
import argparse
import json
import os
import re
import sys

KEYS = [  # (project.json key, C macro, JS field)
    ("project_name", "PROJECT_NAME", "name"),
    ("slug", "PROJECT_SLUG", "slug"),
    ("fw_product", "PROJECT_FW_PRODUCT", "product"),
    ("fwid_magic", "PROJECT_FWID_MAGIC", "magic"),
    ("ap_ssid_prefix", "PROJECT_AP_SSID_PREFIX", "apSsidPrefix"),
    ("mdns_host", "PROJECT_MDNS_HOST", "mdnsHost"),
    ("nvs_namespace", "PROJECT_NVS_NAMESPACE", "nvsNamespace"),
    ("web_session_key", "PROJECT_WEB_SESSION_KEY", "sessionKey"),
]

HEADER_REL = os.path.join("firmware", "include", "project_identity.h")
APPJS_REL = os.path.join("firmware", "web", "app.js")
JSON_REL = "project.json"
JS_LINE_RE = re.compile(r"^([ \t]*)const IDENT = [^\r\n]*", re.M)   # keeps the line ending
SKIP_DIRS = {".pio", ".build_host", "__pycache__", ".git", "node_modules"}

# Lines outside the derived copies that carry a value and are rewritten by --apply:
# (file, line regex, project.json key). Only the matching lines change, and in them only the
# current value: project_name as a whole word, mdns_host as "<host>.local".
TEXT_RULES = [
    ("README.md", r"^# ", "project_name"),
    ("README.pl.md", r"^# ", "project_name"),
    ("NOTICE", r"^\S.* \(project name: project\.json\)$", "project_name"),
    ("mkdocs.yml", r"^site_name: ", "project_name"),
    (os.path.join("firmware", "platformio.ini"), r"^; \S.*: firmware for ", "project_name"),
    (os.path.join("firmware", "src", "net", "net.h"), r"//.*\.local", "mdns_host"),
    (os.path.join("firmware", "src", "net", "wifi_mgr.h"), r"//.*\.local", "mdns_host"),
    (os.path.join("firmware", "src", "net", "wifi_mgr.cpp"), r"//.*\.local", "mdns_host"),
]
# Files that record history: the values in them stay as written (listed as "keep").
HISTORY = {"CHANGELOG.md"}

HEADER_TEMPLATE = """\
// GENERATED from project.json by tools/set_project_name.py. Do not edit by hand.
//
// Project identity in one place. Firmware code uses these macros through version.h (FW_PRODUCT),
// fw_ident.h (FW_IDENT_MAGIC), config.h (NET_AP_SSID_PREFIX, NET_HOSTNAME) and settings.cpp (NVS).
// firmware/tools/project_identity.py reads this file for the Python tools (panel build, mock device).
//
// Compatibility values: PROJECT_FW_PRODUCT and PROJECT_FWID_MAGIC are checked by the Wi-Fi update
// of installed units, PROJECT_NVS_NAMESPACE holds their saved settings. No Arduino.h: also compiled
// on the PC (test_host).
#pragma once

{defines}

// FwIdent::product is char[16]: at most 15 characters plus the terminating zero.
static_assert(sizeof(PROJECT_FW_PRODUCT) <= 16, "PROJECT_FW_PRODUCT too long");
// FwIdent::magic is char[12] = 0x7F + 9 characters + 0x7F + zero (lib/core/fw_ident.h, web/app.js).
static_assert(sizeof(PROJECT_FWID_MAGIC) == 10, "PROJECT_FWID_MAGIC must have exactly 9 characters");
// ESP-IDF NVS namespace: at most 15 characters.
static_assert(sizeof(PROJECT_NVS_NAMESPACE) <= 16, "PROJECT_NVS_NAMESPACE too long");
// Wi-Fi SSID is at most 32 bytes: prefix + 4 hex digits from the MAC address.
static_assert(sizeof(PROJECT_AP_SSID_PREFIX) - 1 + 4 <= 32, "PROJECT_AP_SSID_PREFIX too long");
// mDNS host name label: at most 63 characters.
static_assert(sizeof(PROJECT_MDNS_HOST) <= 64, "PROJECT_MDNS_HOST too long");
"""


def validate(ident):
    errs = []
    for key, _, _ in KEYS:
        v = ident.get(key)
        if not isinstance(v, str) or not v:
            errs.append("%s: missing or empty" % key)
            continue
        if any(ord(c) < 0x20 or ord(c) > 0x7E for c in v) or '"' in v or "\\" in v or "'" in v:
            errs.append("%s: only printable ASCII without quotes and backslashes" % key)
    if errs:
        return errs
    if len(ident["fw_product"]) > 15:
        errs.append("fw_product: at most 15 characters (FwIdent::product)")
    if len(ident["fwid_magic"]) != 9 or "\x7f" in ident["fwid_magic"]:
        errs.append("fwid_magic: exactly 9 characters (FwIdent::magic)")
    if len(ident["nvs_namespace"]) > 15:
        errs.append("nvs_namespace: at most 15 characters (NVS)")
    if len(ident["ap_ssid_prefix"]) + 4 > 32:
        errs.append("ap_ssid_prefix: at most 28 characters (SSID 32 bytes with 4 hex digits)")
    if not re.fullmatch(r"[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?", ident["mdns_host"]):
        errs.append("mdns_host: lower-case letters, digits and '-', at most 63 characters")
    if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", ident["slug"]):
        errs.append("slug: lower-case letters, digits and '-'")
    return errs


def load_json(root):
    with open(os.path.join(root, JSON_REL), encoding="utf-8") as f:
        data = json.load(f)
    return {k: data.get(k) for k, _, _ in KEYS}, data


def render_header(ident):
    defines = "\n".join('#define %-24s "%s"' % (macro, ident[key]) for key, macro, _ in KEYS)
    return HEADER_TEMPLATE.format(defines=defines)


def render_js_line(ident, indent):
    obj = ", ".join("%s: '%s'" % (js, ident[key]) for key, _, js in KEYS)
    return "%sconst IDENT = Object.freeze({ %s });  // from project.json (tools/set_project_name.py)" % (
        indent, obj)


def read(path):
    with open(path, "rb") as f:
        return f.read().decode("utf-8")


def write(path, text):
    with open(path, "wb") as f:
        f.write(text.encode("utf-8"))


def derived_texts(root, ident):
    """Returns {relative path: new text} for the derived copies, or raises ValueError."""
    out = {HEADER_REL: render_header(ident)}
    js = read(os.path.join(root, APPJS_REL))
    found = JS_LINE_RE.findall(js)
    if len(found) != 1:
        raise ValueError("%s: expected exactly one line 'const IDENT = ...', found %d" % (APPJS_REL, len(found)))
    out[APPJS_REL] = JS_LINE_RE.sub(lambda m: render_js_line(ident, m.group(1)), js, count=1)
    return out


def rule_value_re(key, value):
    """The value as it appears in a TEXT_RULES line."""
    if key == "mdns_host":
        return re.compile(r"(?<![0-9A-Za-z-])%s(?=\.local)" % re.escape(value))
    return re.compile(r"(?<![0-9A-Za-z])%s(?![0-9A-Za-z])" % re.escape(value))


def rule_lines(root):
    """Yields (rel, text, list of (line index, key)) for every TEXT_RULES file that exists."""
    by_file = {}
    for rel, line_re, key in TEXT_RULES:
        by_file.setdefault(rel, []).append((re.compile(line_re), key))
    for rel, rules in by_file.items():
        path = os.path.join(root, rel)
        if not os.path.isfile(path):
            continue
        text = read(path)
        marks = []
        for i, line in enumerate(text.splitlines(True)):
            for line_re, key in rules:
                if line_re.search(line):
                    marks.append((i, key))
        yield rel, text, marks


def text_rule_texts(root, cur, new):
    """Returns {relative path: new text} for the TEXT_RULES lines (current values -> new values)."""
    out = {}
    for rel, text, marks in rule_lines(root):
        lines = text.splitlines(True)
        for i, key in marks:
            lines[i] = rule_value_re(key, cur[key]).sub(lambda m, v=new[key]: v, lines[i])
        new_text = "".join(lines)
        if new_text != text:
            out[rel] = new_text
    return out


def check_rules(root, ident):
    """Every TEXT_RULES file must have at least one rule line with the current value."""
    rc = 0
    for rel, line_re, key in TEXT_RULES:
        path = os.path.join(root, rel)
        name = rel.replace(os.sep, "/")
        if not os.path.isfile(path):
            print("MISSING  %s (TEXT_RULES)" % name)
            rc = 1
            continue
        rx_line = re.compile(line_re)
        rx_val = rule_value_re(key, ident[key])
        if not any(rx_line.search(l) and rx_val.search(l) for l in read(path).splitlines()):
            print("DIFFERS  %s: no line /%s/ with the current %s" % (name, line_re, key))
            rc = 1
    if rc == 0:
        print("OK       %d text lines (TEXT_RULES)" % len(TEXT_RULES))
    return rc


def check(root):
    ident, _ = load_json(root)
    errs = validate(ident)
    if errs:
        for e in errs:
            print("project.json: " + e)
        return 1
    try:
        texts = derived_texts(root, ident)
    except ValueError as e:
        print(e)
        return 1
    rc = 0
    for rel, text in texts.items():
        path = os.path.join(root, rel)
        cur = read(path) if os.path.isfile(path) else None
        if cur != text:
            print("DIFFERS  %s (run --regen)" % rel.replace(os.sep, "/"))
            rc = 1
        else:
            print("OK       %s" % rel.replace(os.sep, "/"))
    rc |= check_rules(root, ident)
    return rc


def regen(root, ident):
    errs = validate(ident)
    if errs:
        for e in errs:
            print("invalid: " + e)
        return 1
    for rel, text in derived_texts(root, ident).items():
        write(os.path.join(root, rel), text)
        print("written  %s" % rel.replace(os.sep, "/"))
    return 0


def derive(name, overrides):
    words = re.findall(r"[A-Za-z0-9]+", name)
    if not words:
        raise ValueError("the name needs at least one letter or digit")
    slug = "-".join(w.lower() for w in words)
    alnum = "".join(words)
    ident = {
        "project_name": name,
        "slug": slug,
        "fw_product": slug[:15].rstrip("-"),
        "fwid_magic": (alnum.upper()[:4]).ljust(4, "X") + "-FWID",
        "ap_ssid_prefix": "-".join(words)[:27].rstrip("-") + "-",
        "mdns_host": slug[:63].rstrip("-"),
        "nvs_namespace": alnum.lower()[:15],
        "web_session_key": alnum.lower()[:15] + "pw",
    }
    for item in overrides:
        key, sep, value = item.partition("=")
        if not sep or key not in ident:
            raise ValueError("--set needs key=value with a key from project.json, got %r" % item)
        ident[key] = value
    return ident


def search_terms(ident):
    """(label, regex) for the current values; the mDNS host only as host.local or quoted."""
    terms = []
    seen = set()
    for key, _, _ in KEYS:
        v = ident[key]
        if key == "mdns_host":
            terms.append((key, re.compile(r"%s\.local|[\"']%s[\"']" % (re.escape(v), re.escape(v)))))
            continue
        if v in seen:
            continue
        seen.add(v)
        # not inside a longer word or hex number (e.g. "c508" in a KiCad UUID); "_" counts as a
        # boundary so that file names such as "<slug>_can.log" are found
        terms.append((key, re.compile(r"(?<![0-9A-Za-z])%s(?![0-9A-Za-z])" % re.escape(v))))
    return terms


def places(root, ident):
    managed = {JSON_REL, HEADER_REL, APPJS_REL}
    rule_marks = {}
    for rel, _, marks in rule_lines(root):
        rule_marks[rel.replace(os.sep, "/")] = {i + 1 for i, _ in marks}
    terms = search_terms(ident)
    hits = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for fn in sorted(filenames):
            path = os.path.join(dirpath, fn)
            rel = os.path.relpath(path, root)
            try:
                with open(path, "rb") as f:
                    data = f.read()
            except OSError:
                continue
            if b"\x00" in data[:4096] and not fn.endswith((".txt", ".log")):
                binary = True
            else:
                binary = False
            text = data.decode("utf-8", "replace")
            for no, line in enumerate(text.splitlines(), 1):
                labels = [lab for lab, rx in terms if rx.search(line)]
                if not labels:
                    continue
                if rel == APPJS_REL and not JS_LINE_RE.match(line):
                    kind = "REVIEW"
                elif rel in managed or no in rule_marks.get(rel.replace(os.sep, "/"), ()):
                    kind = "auto"
                elif rel.replace(os.sep, "/") in HISTORY:
                    kind = "keep"
                else:
                    kind = "REVIEW"
                shown = "(binary file)" if binary else line.strip()[:110]
                hits.append((kind, rel.replace(os.sep, "/"), no, ",".join(labels), shown))
                if binary:
                    break
    return hits


def main():
    ap = argparse.ArgumentParser(description="Project identity in one place (project.json).")
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--check", action="store_true", help="derived copies match project.json")
    g.add_argument("--regen", action="store_true", help="rewrite the derived copies from project.json")
    g.add_argument("--dry-run", metavar="NEW_NAME", help="show new values and every place to review")
    g.add_argument("--apply", metavar="NEW_NAME", help="write project.json and the derived copies")
    ap.add_argument("--set", action="append", default=[], metavar="KEY=VALUE", help="override a derived value")
    ap.add_argument("--root", default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                    help="repository root (default: the parent of tools/)")
    args = ap.parse_args()
    root = os.path.abspath(args.root)

    if args.check:
        return check(root)
    cur, data = load_json(root)
    if args.regen:
        return regen(root, cur)

    name = args.dry_run if args.dry_run is not None else args.apply
    try:
        new = derive(name, args.set)
    except ValueError as e:
        print(e)
        return 2
    errs = validate(new)
    print("%-16s %-24s %s" % ("key", "current", "new"))
    for key, _, _ in KEYS:
        mark = "" if cur[key] == new[key] else "   (changes)"
        print("%-16s %-24s %s%s" % (key, cur[key], new[key], mark))
    for e in errs:
        print("invalid: " + e)
    if errs:
        return 1

    if args.dry_run is not None:
        hits = places(root, cur)
        print("")
        print("Places with the current values (auto = rewritten by --apply, keep = history, REVIEW = by hand):")
        for kind, rel, no, labels, shown in hits:
            print("%-6s %s:%d [%s] %s" % (kind, rel, no, labels, shown))
        auto = sum(1 for h in hits if h[0] == "auto")
        keep = sum(1 for h in hits if h[0] == "keep")
        print("")
        print("%d places: %d auto, %d keep, %d to review. Nothing was written (dry run)." % (
            len(hits), auto, keep, len(hits) - auto - keep))
        return 0

    texts = text_rule_texts(root, cur, new)    # from the current values, before project.json changes
    data.update(new)
    write(os.path.join(root, JSON_REL), json.dumps(data, indent=2, ensure_ascii=True) + "\n")
    print("written  %s" % JSON_REL)
    for rel, text in texts.items():
        write(os.path.join(root, rel), text)
        print("written  %s" % rel.replace(os.sep, "/"))
    return regen(root, new)


if __name__ == "__main__":
    sys.exit(main())
