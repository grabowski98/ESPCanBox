// "word" at the start of the text, followed by the end or a space. 'rest' = text after the space (or empty).
static bool takeWord(const char* s, const char* word, const char*& rest) {
    size_t n = strlen(word);
    if (strncmp(s, word, n) != 0) return false;
    if (s[n] == 0) {
        rest = s + n;
        return true;
    }
    if (s[n] == ' ') {
        rest = s + n + 1;
        return true;
    }
    return false;
}

static void cmdSta(const char* arg, uint32_t nowMs) {
    if (strcmp(arg, "off") == 0) {
        printSetResult(settingsClearSta(), "[wifi] home network forgotten");
        noteDuringUpload();
        scheduleApply(nowMs, 0);
        return;
    }
    // Split at the FIRST '|' character: name|password.
    const char* bar = strchr(arg, '|');
    size_t ssidLen = bar ? (size_t)(bar - arg) : 0;
    size_t passLen = bar ? strlen(bar + 1) : 0;
    if (bar == nullptr || ssidLen == 0 || ssidLen > SET_SSID_MAX || passLen > SET_STA_PASS_MAX) {
        conPrintln("[wifi] usage: wifi sta <name>|<password> (name 1..32, password 8..63 characters or 64 hex digits) or wifi sta off");
        return;
    }
    char ssid[SET_SSID_MAX + 1];
    char pass[SET_STA_PASS_MAX + 1];
    memcpy(ssid, arg, ssidLen);
    ssid[ssidLen] = 0;
    memcpy(pass, bar + 1, passLen);
    pass[passLen] = 0;
    SetResult res = settingsStaAcceptable(ssid, pass) ? settingsSetSta(ssid, pass) : SetResult::INVALID;
    volatile char* v = pass;   // the home network password does not stay on the stack
    for (size_t i = 0; i < sizeof(pass); i++) v[i] = 0;
    if (res == SetResult::INVALID) {
        conPrintln("[wifi] home network: name 1..32 characters, password 8..63 characters or 64 hex digits (open networks are not supported)");
        return;
    }
    printSetResult(res, "[wifi] home network stored");
    if (res == SetResult::OK) {
        noteDuringUpload();
        scheduleApply(nowMs, 0);
    }
}

static void cmdNewPassword(uint32_t nowMs) {
    WifiStatus ws;
    wifiMgrGetStatus(ws);
    if (ws.phase == WifiPhase::RUNNING) {
        // The radio is running: esp_fill_random gives true randomness. New password right away, with no moment without a password.
        char pw[webauth::PASSWORD_MAX + 1];
        SetResult res = settingsGeneratePassword(pw, sizeof(pw)) ? settingsSetDevicePassword(pw) : SetResult::INVALID;
        volatile char* v = pw;
        for (size_t i = 0; i < sizeof(pw); i++) v[i] = 0;
        if (res != SetResult::OK) {
            conPrintln("[wifi] could not store the new password; the old one stays");
            return;
        }
    } else {
        // The radio is not running (or is just starting): the network start generates the password (step 1).
        if (settingsClearDevicePassword() != SetResult::OK) {
            conPrintln("[wifi] settings write failed; the old password stays");
            return;
        }
    }
    conPrintln("[wifi] the old password stops working on all devices");
    conPrintln("[wifi] the new password is shown by the command: wifi showpass");
    noteDuringUpload();
    scheduleApply(nowMs, 0);
}

bool netConsoleCommand(const char* line, bool fromUsb, uint32_t nowMs) {
    const char* arg = nullptr;
    if (line == nullptr || !takeWord(line, "wifi", arg)) return false;
    if (!fromUsb) {
        conPrintln("[wifi] USB console only");
        return true;
    }
    if (!s_ok) {
        conPrintln("[wifi] the network did not start at this boot");
        return true;
    }
    const char* rest = nullptr;
    if (arg[0] == 0) {
        wifiMgrPrintInfo();
        if (!s_netEnabled) conPrintln("[wifi] disabled by the command wifi off");
        if (s_blocked) conPrintln("[wifi] network held after crash restarts; wifi on enables it again");
    } else if (strcmp(arg, "showpass") == 0 || strcmp(arg, "haslo") == 0) {   // "haslo": old name, kept as an alias
        wifiMgrPrintPassword();   // USB only
    } else if (takeWord(arg, "pass", rest) && rest[0] != 0) {
        if (!webauth::passwordAcceptable(rest)) {
            conPrintln("[wifi] password: 10..63 printable characters, no spaces");
            return true;
        }
        SetResult res = settingsSetDevicePassword(rest);
        printSetResult(res, "[wifi] new device password stored; the network restarts");
        if (res == SetResult::OK) {
            noteDuringUpload();
            scheduleApply(nowMs, 0);
        }
    } else if (takeWord(arg, "sta", rest) && rest[0] != 0) {
        cmdSta(rest, nowMs);
    } else if (strcmp(arg, "lan on") == 0 || strcmp(arg, "lan off") == 0) {
        bool on = strcmp(arg, "lan on") == 0;
        printSetResult(settingsSetLanAdmin(on), on ? "[wifi] changes from the home network: allowed"
                                                   : "[wifi] changes from the home network: blocked");
    } else if (strcmp(arg, "on") == 0) {
        SetResult res = settingsSetNetEnabled(true);
        if (res == SetResult::OK) s_netEnabled = true;
        clearFaults();               // also the hold after fault restarts
        wifiMgrClearFailures();
        printSetResult(res, "[wifi] enabled");
    } else if (strcmp(arg, "off") == 0) {
        SetResult res = settingsSetNetEnabled(false);
        if (res == SetResult::OK) s_netEnabled = false;
        printSetResult(res, "[wifi] disabled (kept after a restart); wifi on enables");
        if (res == SetResult::OK) noteDuringUpload();
    } else if (strcmp(arg, "newpass") == 0 || strcmp(arg, "nowehaslo") == 0) {   // "nowehaslo": old name, alias
        cmdNewPassword(nowMs);
    } else {
        conPrintln("[wifi] commands: wifi | wifi showpass | wifi pass <password> | wifi sta <name>|<password> | "
                   "wifi sta off | wifi lan on|off | wifi on | wifi off | wifi newpass");
    }
    return true;
}

