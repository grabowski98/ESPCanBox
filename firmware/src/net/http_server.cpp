static esp_err_t handleFavicon(httpd_req_t* req);
static esp_err_t handleIndex(httpd_req_t* req);
static esp_err_t handleI18n(httpd_req_t* req);

// One exact address per separate panel dictionary (web_assets.h, WEB_I18N): GET /i18n/<lang>.json.
static bool registerI18n(httpd_handle_t h) {
    for (size_t i = 0; i < WEB_I18N_COUNT; i++) {
        if (!httpRegister(h, WEB_I18N[i].uri, HTTP_GET, handleI18n)) return false;
    }
    return true;
}

bool httpServerStart() {
    if (s_server != nullptr) return true;

    httpd_config_t cfg = HTTPD_DEFAULT_CONFIG();
    cfg.task_priority = HTTP_TASK_PRIO;
    cfg.stack_size = HTTP_TASK_STACK;
    cfg.core_id = HTTP_TASK_CORE;
    cfg.max_req_hdr_len = HTTP_REQ_HDR_MAX;
    cfg.server_port = HTTP_PORT;
    cfg.max_open_sockets = HTTP_MAX_SOCKETS;
    cfg.max_uri_handlers = HTTP_MAX_ROUTES;
    cfg.max_resp_headers = HTTP_MAX_RESP_HEADERS;
    cfg.lru_purge_enable = true;          // when all connections are taken close the least recently used one
    cfg.recv_wait_timeout = HTTP_RECV_TIMEOUT_S;
    cfg.send_wait_timeout = HTTP_SEND_TIMEOUT_S;
    cfg.open_fn = onOpen;                 // total deadlines: headers (sessRecv), response (sessSend); close_fn default
    // uri_match_fn stays NULL: exact address comparison (registration order in http_server.h).

    s_stopRequested = false;
    httpd_handle_t h = nullptr;
    esp_err_t e = httpd_start(&h, &cfg);
    if (e != ESP_OK || h == nullptr) {
        conLogf("[www] server did not start: %s", esp_err_to_name(e));
        return false;
    }
    // Order: longer addresses before shorter ones with the same beginning, "/" at the end.
    bool ok = otaRegisterRoutes(h) && apiRegisterRoutes(h) && registerI18n(h) &&
              httpRegister(h, "/favicon.ico", HTTP_GET, handleFavicon) &&
              httpRegister(h, "/", HTTP_GET, handleIndex);
    if (!ok) {
        httpd_stop(h);
        return false;
    }
    s_server = h;
    return true;
}

void httpServerStop() {
    s_stopRequested = true;               // first: long loops end at the next portion
    httpd_handle_t h = s_server;
    if (h == nullptr) return;
    httpd_stop(h);                        // waits for the running request to end
    s_server = nullptr;
}

bool httpServerRunning() { return s_server != nullptr; }
bool httpStopRequested() { return s_stopRequested; }

bool httpRegister(httpd_handle_t server, const char* uri, httpd_method_t method, esp_err_t (*handler)(httpd_req_t*)) {
    httpd_uri_t u = {};
    u.uri = uri;
    u.method = method;
    u.handler = handlerTrampoline;        // header clock (sessRecv), then the real function
    u.user_ctx = (void*)handler;
    esp_err_t e = httpd_register_uri_handler(server, &u);
    if (e != ESP_OK) {
        conLogf("[www] registration %s failed: %s", uri, esp_err_to_name(e));
        return false;
    }
    return true;
}

// ---------- responses ----------

const char* httpStatusText(HttpStatus status) {
    switch (status) {
        case HttpStatus::OK: return "200 OK";
        case HttpStatus::BAD_REQUEST: return "400 Bad Request";
        case HttpStatus::UNAUTHORIZED: return "401 Unauthorized";
        case HttpStatus::FORBIDDEN: return "403 Forbidden";
        case HttpStatus::CONFLICT: return "409 Conflict";
        case HttpStatus::LENGTH_REQUIRED: return "411 Length Required";
        case HttpStatus::TOO_LARGE: return "413 Content Too Large";
        case HttpStatus::TOO_MANY: return "429 Too Many Requests";
        case HttpStatus::INTERNAL: return "500 Internal Server Error";
        case HttpStatus::UNAVAILABLE: return "503 Service Unavailable";
    }
    return "500 Internal Server Error";
}

char* httpBuf() { return s_buf; }

// Common headers of JSON responses. All values are constant texts (the server keeps pointers).
static esp_err_t sendJsonText(httpd_req_t* req, HttpStatus status, const char* text, size_t len) {
    httpd_resp_set_status(req, httpStatusText(status));
    httpd_resp_set_type(req, HTTPD_TYPE_JSON);
    httpd_resp_set_hdr(req, "Cache-Control", "no-store");
    httpd_resp_set_hdr(req, "X-Content-Type-Options", "nosniff");
    return httpd_resp_send(req, text, (ssize_t)len);
}

esp_err_t httpSendError(httpd_req_t* req, HttpStatus status, const char* code, const char* detail) {
    char b[192];
    JsonWriter j(b, sizeof(b));
    j.beginObject();
    j.key("error");
    j.str(code);
    if (detail != nullptr) {
        j.key("detail");
        j.str(detail);
    }
    j.endObject();
    if (!j.ok()) {                        // 'detail' too long: the error code alone
        j.reset();
        j.beginObject();
        j.key("error");
        j.str(code);
        j.endObject();
    }
    return sendJsonText(req, status, j.c_str(), j.length());
}

esp_err_t httpSendJson(httpd_req_t* req, const JsonWriter& j, HttpStatus status) {
    if (!j.ok()) return httpSendError(req, HttpStatus::INTERNAL, "overflow");
    return sendJsonText(req, status, j.c_str(), j.length());
}

// ---------- request body ----------

bool httpDiscardBody(httpd_req_t* req, size_t remaining, uint32_t deadlineMs) {
    while (remaining > 0) {
        if (s_stopRequested) return false;
        if ((int32_t)(millis() - deadlineMs) >= 0) return false;
        size_t n = remaining < HTTP_BUF_SIZE ? remaining : HTTP_BUF_SIZE;
        int r = httpd_req_recv(req, s_buf, n);
        if (r == HTTPD_SOCK_ERR_TIMEOUT) continue;    // a single receive waited HTTP_RECV_TIMEOUT_S; deadline above
        if (r <= 0) return false;
        remaining -= (size_t)r;
        // Yield the processor: the core 0 idle task is guarded by the watchdog (5 s).
        vTaskDelay(1);
    }
    return true;
}

// Discards the body (up to 'maxDrain' bytes, within HTTP_DRAIN_DEADLINE_MS), then sends the error.
// Result for the handler: ESP_OK only when the body was read entirely and sending succeeded;
// otherwise ESP_FAIL (the server closes the connection, because unread bytes remain in the socket).
static esp_err_t rejectWithBody(httpd_req_t* req, size_t maxDrain, HttpStatus status, const char* code,
                                const char* jsonOverride = nullptr, size_t jsonLen = 0) {
    size_t total = req->content_len;
    bool drained = true;
    if (total > 0) {
        drained = (total <= maxDrain) && httpDiscardBody(req, total, millis() + HTTP_DRAIN_DEADLINE_MS);
    }
    if (s_stopRequested) return ESP_FAIL;
    esp_err_t e = (jsonOverride != nullptr) ? sendJsonText(req, status, jsonOverride, jsonLen)
                                            : httpSendError(req, status, code);
    return (drained && e == ESP_OK) ? ESP_OK : ESP_FAIL;
}

bool httpReadForm(httpd_req_t* req, const char*& body, size_t& len, esp_err_t& ret) {
    body = s_form;
    len = 0;
    s_form[0] = 0;
    size_t total = req->content_len;
    if (total == 0) {
        ret = httpSendError(req, HttpStatus::LENGTH_REQUIRED, "length_required");
        return false;
    }
    if (total > HTTP_FORM_MAX) {
        ret = rejectWithBody(req, HTTP_FORM_DRAIN_MAX, HttpStatus::TOO_LARGE, "too_large");
        return false;
    }
    // Total deadline: a client sending one byte every few seconds will not occupy the only server task.
    // A single receive may still wait HTTP_RECV_TIMEOUT_S, so the worst case is
    // HTTP_DRAIN_DEADLINE_MS + HTTP_RECV_TIMEOUT_S.
    uint32_t deadline = millis() + HTTP_DRAIN_DEADLINE_MS;
    size_t got = 0;
    while (got < total) {
        if (s_stopRequested || (int32_t)(millis() - deadline) >= 0) {
            ret = ESP_FAIL;
            return false;
        }
        int r = httpd_req_recv(req, s_form + got, total - got);
        if (r <= 0) {                     // error, closed connection or receive timeout
            ret = ESP_FAIL;
            return false;
        }
        got += (size_t)r;
    }
    s_form[got] = 0;
    len = got;
    ret = ESP_OK;
    return true;
}

// ---------- URL parameters ----------

// Parameter text (the part after '?') into 'q'. 0 = none or longer than HTTP_QUERY_MAX - 1 (skipped entirely).
static size_t getQuery(httpd_req_t* req, char* q, size_t cap) {
    q[0] = 0;
    size_t n = httpd_req_get_url_query_len(req);
    if (n == 0 || n > cap - 1) return 0;
    if (httpd_req_get_url_query_str(req, q, cap) != ESP_OK) {
        q[0] = 0;
        return 0;
    }
    return strnlen(q, cap);
}

// Whether the text "a=1&b=2" has a field named 'key' (also with an empty value). A pair without '=' is not
// a field: the same rules as webauth::formValue.
static bool queryHasKey(const char* q, size_t qlen, const char* key) {
    size_t klen = strlen(key);
    size_t i = 0;
    while (i < qlen) {
        size_t start = i;
        while (i < qlen && q[i] != '&') i++;
        size_t end = i;                    // field q[start..end)
        size_t nameEnd = start;
        while (nameEnd < end && q[nameEnd] != '=') nameEnd++;
        if (nameEnd < end && nameEnd - start == klen && memcmp(q + start, key, klen) == 0) return true;
        i++;                               // past the '&' character
    }
    return false;
}

bool httpQueryValue(httpd_req_t* req, const char* key, char* out, size_t cap) {
    if (cap > 0) out[0] = 0;
    char q[HTTP_QUERY_MAX];
    size_t qlen = getQuery(req, q, sizeof(q));
    if (qlen == 0) return false;
    if (!webauth::formValue(q, qlen, key, out, cap)) {
        if (cap > 0) out[0] = 0;
        return false;
    }
    return true;
}

bool httpQueryU32(httpd_req_t* req, const char* key, uint32_t& out, bool& present) {
    out = 0;
    present = false;
    char q[HTTP_QUERY_MAX];
    size_t qlen = getQuery(req, q, sizeof(q));
    if (qlen == 0) return false;
    if (!queryHasKey(q, qlen, key)) return false;
    present = true;
    char v[12];
    if (!webauth::formValue(q, qlen, key, v, sizeof(v))) return false;
    size_t n = strlen(v);
    if (n == 0 || n > 10) return false;
    uint64_t acc = 0;
    for (size_t i = 0; i < n; i++) {
        if (v[i] < '0' || v[i] > '9') return false;
        acc = acc * 10 + (uint64_t)(v[i] - '0');
    }
    if (acc > 0xFFFFFFFFull) return false;
    out = (uint32_t)acc;
    return true;
}

// ---------- login ----------

uint32_t httpLoginLockedS() {
    uint32_t ms = s_guard.lockedForMs(millis());
    return (ms + 999) / 1000;             // round up
}

bool httpRequireAuth(httpd_req_t* req, esp_err_t& ret, HttpAccess access) {
    char pass[webauth::PASSWORD_MAX + 1];

    // 0. Without a valid device password nobody gets in (the "no password" state is closed).
    if (!settingsGetDevicePassword(pass, sizeof(pass)) || !webauth::passwordAcceptable(pass)) {
        wipe(pass, sizeof(pass));
        ret = rejectWithBody(req, HTTP_FORM_MAX, HttpStatus::UNAVAILABLE, "not_ready");
        return false;
    }

    const bool fromAp = httpPeerIsAp(req);
    const uint32_t now = millis();
    s_guard.poll(now);                    // a finished lockout cannot come back after the millis() wrap
    if (s_haveLastBad && (uint32_t)(now - s_lastBadMs) >= webauth::LoginGuard::FAIL_WINDOW_MS) wipeLastBad();

    // 1. Lockout after wrong passwords (only clients outside the own network), also for a correct password.
    if (!fromAp) {
        uint32_t lockMs = s_guard.lockedForMs(now);
        if (lockMs > 0) {
            wipe(pass, sizeof(pass));
            char b[64];
            JsonWriter j(b, sizeof(b));
            j.beginObject();
            j.key("error");
            j.str("locked");
            j.key("retryInS");
            j.unum((lockMs + 999) / 1000);
            j.endObject();
            ret = rejectWithBody(req, HTTP_FORM_MAX, HttpStatus::TOO_MANY, "locked", j.c_str(), j.length());
            return false;
        }
    }

    // 2. No header: 401, not counted as a failed attempt.
    size_t hlen = httpd_req_get_hdr_value_len(req, "Authorization");
    if (hlen == 0) {
        wipe(pass, sizeof(pass));
        ret = rejectWithBody(req, HTTP_FORM_MAX, HttpStatus::UNAUTHORIZED, "auth");
        return false;
    }

    // 3. Read and compare. The password comparison is performed ALWAYS (also with a wrong name
    //    and an unreadable header), so that the response time does not reveal what was wrong.
    char user[16];
    char given[webauth::PASSWORD_MAX + 1];
    user[0] = 0;
    given[0] = 0;
    bool parsed = false;
    {
        char hdr[HTTP_AUTH_HDR_MAX];
        if (hlen < sizeof(hdr) && httpd_req_get_hdr_value_str(req, "Authorization", hdr, sizeof(hdr)) == ESP_OK) {
            parsed = webauth::parseBasic(hdr, user, sizeof(user), given, sizeof(given));
        }
        wipe(hdr, sizeof(hdr));
    }
    if (!parsed) {
        user[0] = 0;
        given[0] = 0;
    }
    const bool passOk = webauth::constantTimeEquals(given, pass);
    const bool userOk = parsed && strcmp(user, HTTP_AUTH_USER) == 0;
    wipe(pass, sizeof(pass));

    if (!(parsed && userOk && passOk)) {
        if (!fromAp) {
            // The same wrong value as in the previous failed attempt does not count a second time.
            bool repeat = s_haveLastBad && webauth::constantTimeEquals(given, s_lastBadPass);
            if (!repeat) {
                s_guard.onFailure(now);
                memcpy(s_lastBadPass, given, sizeof(s_lastBadPass));
                s_lastBadPass[sizeof(s_lastBadPass) - 1] = 0;
                s_haveLastBad = true;
            }
            s_lastBadMs = now;            // an old tab repeating it keeps it recognised
        }
        wipe(given, sizeof(given));
        // Only a constant text and the client address go to the log; never the given name or password.
        uint8_t ip[4];
        if (sockIpv4(req, false, ip)) {
            conLogf("[www] failed login from %u.%u.%u.%u", ip[0], ip[1], ip[2], ip[3]);
        } else {
            conLogf("[www] failed login");
        }
        ret = rejectWithBody(req, HTTP_FORM_MAX, HttpStatus::UNAUTHORIZED, "auth");
        return false;
    }
    wipe(given, sizeof(given));

    // 4. Changes from the home network only after "wifi lan on" on USB.
    if (access == HttpAccess::WRITE && !fromAp && !settingsLanAdmin()) {
        ret = rejectWithBody(req, HTTP_FORM_MAX, HttpStatus::FORBIDDEN, "ap_only");
        return false;
    }

    // 5. Correct login. LoginGuard applies only to clients outside the own network.
    if (!fromAp) s_guard.onSuccess(now);
    wipeLastBad();
    diagTouchClient(millis());
    ret = ESP_OK;
    return true;
}

