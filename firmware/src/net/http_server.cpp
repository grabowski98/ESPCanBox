// Server handle. Changed only by the net_wifi task (start / stop); may be read from any task.
static httpd_handle_t volatile s_server = nullptr;
// Stop request: long handler loops check it after every portion.
static volatile bool s_stopRequested = false;

// ---------- web task buffers (a single task only, requests do not overlap) ----------

static char s_buf[HTTP_BUF_SIZE];             // shared working buffer (httpBuf)
static char s_form[HTTP_FORM_MAX + 1];        // form body (httpReadForm)

// Lockout after wrong passwords: one for all clients outside the device's own network.
static webauth::LoginGuard s_guard;
// Password of the last failed attempt (only clients outside the own network). Repeating the same
// wrong password (e.g. an old browser tab polling every 0.5 s) does not increase the failure counter.
// Kept only for LoginGuard::FAIL_WINDOW_MS after the last such attempt and wiped after a correct login (review:
// it held, in plain text, usually a mistyped real password for the whole uptime).
static char s_lastBadPass[webauth::PASSWORD_MAX + 1];
static bool s_haveLastBad = false;
static uint32_t s_lastBadMs = 0;

// Zeroing a password buffer. Volatile pointer: the compiler must not drop the write as "redundant".
static void wipe(void* p, size_t n) {
    volatile uint8_t* v = (volatile uint8_t*)p;
    while (n--) *v++ = 0;
}

static void wipeLastBad() {
    if (!s_haveLastBad) return;
    wipe(s_lastBadPass, sizeof(s_lastBadPass));
    s_haveLastBad = false;
}

// ---------- client address ----------

// IPv4 address of one side of the connection: local = false -> the other side (getpeername), true -> our
// address the connection came to (getsockname). The server may accept connections on an IPv6 socket
// (LWIP_IPV4 and LWIP_IPV6 enabled in sdkconfig), then the IPv4 address has the form ::ffff:a.b.c.d.
static bool sockIpv4(httpd_req_t* req, bool local, uint8_t ip[4]) {
    int fd = httpd_req_to_sockfd(req);
    if (fd < 0) return false;
    struct sockaddr_storage ss;
    memset(&ss, 0, sizeof(ss));
    socklen_t len = sizeof(ss);
    int r = local ? getsockname(fd, (struct sockaddr*)&ss, &len) : getpeername(fd, (struct sockaddr*)&ss, &len);
    if (r != 0) return false;
    if (ss.ss_family == AF_INET) {
        struct sockaddr_in a;
        memcpy(&a, &ss, sizeof(a));
        memcpy(ip, &a.sin_addr.s_addr, 4);       // network byte order: ip[0] = first byte of the address
        return true;
    }
    if (ss.ss_family == AF_INET6) {
        struct sockaddr_in6 a;
        memcpy(&a, &ss, sizeof(a));
        const uint8_t* b = a.sin6_addr.s6_addr;
        for (int i = 0; i < 10; i++) {
            if (b[i] != 0) return false;           // a real IPv6 address: not our subnet
        }
        if (b[10] != 0xFF || b[11] != 0xFF) return false;
        memcpy(ip, b + 12, 4);
        return true;
    }
    return false;
}

bool httpPeerIsAp(httpd_req_t* req) {
    // Both conditions at once. The client address alone can be spoofed from the home network: lwIP chooses the reply
    // interface by the SOURCE address (LWIP_HOOK_IP4_ROUTE_SRC), so a SYN to the STA address with a spoofed
    // 10.50.8.x gets a reply via STA. A connection to the device address NET_AP_IP with a spoofed
    // source from the home network gets the reply via the AP interface, so it is not established.
    uint8_t loc[4];
    if (!sockIpv4(req, true, loc)) return false;
    if (memcmp(loc, NET_AP_IP, 4) != 0) return false;    // the connection came to the STA address
    uint8_t ip[4];
    if (!sockIpv4(req, false, ip)) return false;
    // Subnet of the device's own network: NET_AP_IP/24.
    return ip[0] == NET_AP_IP[0] && ip[1] == NET_AP_IP[1] && ip[2] == NET_AP_IP[2];
}

// ---------- total deadline for the request headers ----------
//
// esp_http_server only has a limit for a single receive (HTTP_RECV_TIMEOUT_S), counted from every byte.
// That is why every connection gets its own receive function (httpd_sess_set_recv_override in onOpen),
// which measures the time of the WHOLE reception outside the handlers: the request line, the headers and discarding
// the unread body after handling. After HTTP_HDR_DEADLINE_MS it returns an error and the server closes the connection.
// Inside the handlers (entered via handlerTrampoline) the deadline does not apply: there their own
// deadlines take care of it (HTTP_DRAIN_DEADLINE_MS, upload limits in ota.cpp).
// Everything only in the server task (onOpen, sessRecv, trampoline): no locks.

struct HdrClock {
    bool running;          // reception outside a handler in progress
    uint32_t startMs;      // start of this reception
    uint32_t lastMs;       // end of the last receive on this socket
};
// Index = lwIP socket number - LWIP_SOCKET_OFFSET (lwIP socket numbers are consecutive, starting from this offset).
static HdrClock s_hdrClock[CONFIG_LWIP_MAX_SOCKETS];
// Total send deadline of the response being sent by a handler on this socket (sessSend, HTTP_SEND_DEADLINE_MS).
static SendDeadline s_sendClock[CONFIG_LWIP_MAX_SOCKETS];
static bool s_inHandler = false;       // a handler is running (trampoline)

static HdrClock* hdrClock(int fd) {
    int i = fd - LWIP_SOCKET_OFFSET;
    if (i < 0 || i >= (int)CONFIG_LWIP_MAX_SOCKETS) return nullptr;    // outside the table: no deadline
    return &s_hdrClock[i];
}

static SendDeadline* sendClock(int fd) {
    int i = fd - LWIP_SOCKET_OFFSET;
    if (i < 0 || i >= (int)CONFIG_LWIP_MAX_SOCKETS) return nullptr;
    return &s_sendClock[i];
}

// Receive like the default in esp_http_server (recv + the same error codes) with a total deadline.
static int sessRecv(httpd_handle_t hd, int fd, char* buf, size_t len, int flags) {
    (void)hd;
    if (buf == nullptr) return HTTPD_SOCK_ERR_INVALID;
    HdrClock* c = hdrClock(fd);
    uint32_t now = millis();
    if (c != nullptr && !s_inHandler) {
        // New request: the first receive after a handler or after a pause on a keep-alive connection.
        if (!c->running || (uint32_t)(now - c->lastMs) > HTTP_HDR_IDLE_RESET_MS) {
            c->running = true;
            c->startMs = now;
        } else if ((uint32_t)(now - c->startMs) >= HTTP_HDR_DEADLINE_MS) {
            c->running = false;
            conLogf("[www] request too slow: disconnected");
            return HTTPD_SOCK_ERR_FAIL;   // the server closes the connection without a response
        }
    }
    int r = recv(fd, buf, len, flags);   // the socket has the limit SO_RCVTIMEO = HTTP_RECV_TIMEOUT_S (server)
    if (c != nullptr) c->lastMs = millis();
    if (r < 0) {
        if (errno == EAGAIN || errno == EWOULDBLOCK || errno == EINTR) return HTTPD_SOCK_ERR_TIMEOUT;
        return HTTPD_SOCK_ERR_FAIL;
    }
    return r;
}

// Send like the default in esp_http_server (send + the same error codes) with a total deadline per response
// sent by a handler. Responses the server sends by itself (outside a handler, e.g. 404) are short: no deadline.
static int sessSend(httpd_handle_t hd, int fd, const char* buf, size_t len, int flags) {
    (void)hd;
    if (buf == nullptr) return HTTPD_SOCK_ERR_INVALID;
    SendDeadline* d = sendClock(fd);
    if (d != nullptr && s_inHandler && !d->allow(millis(), HTTP_SEND_DEADLINE_MS)) {
        conLogf("[www] response read too slowly: disconnected");
        return HTTPD_SOCK_ERR_FAIL;       // the handler gets an error, the server closes the connection
    }
    int r = send(fd, buf, len, flags);    // the socket has the limit SO_SNDTIMEO = HTTP_SEND_TIMEOUT_S (server)
    if (r < 0) {
        if (errno == EAGAIN || errno == EWOULDBLOCK || errno == EINTR) return HTTPD_SOCK_ERR_TIMEOUT;
        return HTTPD_SOCK_ERR_FAIL;
    }
    return r;
}

// New connection: clean clocks and our own receive and send functions.
static esp_err_t onOpen(httpd_handle_t hd, int fd) {
    HdrClock* c = hdrClock(fd);
    if (c != nullptr) {
        c->running = false;
        c->lastMs = millis();
    }
    SendDeadline* d = sendClock(fd);
    if (d != nullptr) d->reset();
    esp_err_t e = httpd_sess_set_recv_override(hd, fd, sessRecv);
    if (e != ESP_OK) return e;
    return httpd_sess_set_send_override(hd, fd, sessSend);
}

// All addresses registered via httpRegister enter here (the real function is in user_ctx).
// Entering the handler ends the header reception; after leaving it the next receive is counted afresh.
static esp_err_t handlerTrampoline(httpd_req_t* req) {
    esp_err_t (*fn)(httpd_req_t*) = (esp_err_t (*)(httpd_req_t*))req->user_ctx;
    const int fd = httpd_req_to_sockfd(req);
    HdrClock* c = hdrClock(fd);
    if (c != nullptr) c->running = false;
    SendDeadline* d = sendClock(fd);
    if (d != nullptr) d->reset();         // the send deadline of this response starts at its first send
    s_inHandler = true;
    esp_err_t r = fn(req);
    s_inHandler = false;
    if (c != nullptr) c->running = false;
    return r;
}

