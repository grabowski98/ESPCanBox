static esp_err_t handleIndex(httpd_req_t* req) {
    // The If-None-Match header is read before the first send (the server discards it afterwards).
    bool notModified = false;
    char inm[48];
    size_t l = httpd_req_get_hdr_value_len(req, "If-None-Match");
    if (l > 0 && l < sizeof(inm) && httpd_req_get_hdr_value_str(req, "If-None-Match", inm, sizeof(inm)) == ESP_OK) {
        notModified = strcmp(inm, WEB_INDEX_ETAG) == 0;
    }
    httpd_resp_set_hdr(req, "Cache-Control", "no-cache");
    httpd_resp_set_hdr(req, "ETag", WEB_INDEX_ETAG);
    if (notModified) {
        httpd_resp_set_status(req, "304 Not Modified");
        return httpd_resp_send(req, nullptr, 0);
    }
    // The page is always gzip-compressed (also without Accept-Encoding; browsers always send it).
    httpd_resp_set_type(req, "text/html; charset=utf-8");
    httpd_resp_set_hdr(req, "Content-Encoding", "gzip");
    httpd_resp_set_hdr(req, "X-Frame-Options", "DENY");
    httpd_resp_set_hdr(req, "X-Content-Type-Options", "nosniff");
    httpd_resp_set_hdr(req, "Referrer-Policy", "no-referrer");
    httpd_resp_set_hdr(req, "Content-Security-Policy", WEB_INDEX_CSP);
    return httpd_resp_send(req, (const char*)WEB_INDEX_GZ, (ssize_t)WEB_INDEX_GZ_LEN);
}

// A panel dictionary (no login: the same texts are in the public repository, no device data, read only).
// The request address chooses the table row; the part after '?' is ignored, as by the server itself.
static esp_err_t handleI18n(httpd_req_t* req) {
    const WebI18nAsset* a = nullptr;
    size_t ulen = strcspn(req->uri, "?");
    for (size_t i = 0; i < WEB_I18N_COUNT; i++) {
        if (strlen(WEB_I18N[i].uri) == ulen && strncmp(WEB_I18N[i].uri, req->uri, ulen) == 0) {
            a = &WEB_I18N[i];
            break;
        }
    }
    if (a == nullptr) {                       // cannot happen: only table addresses are registered
        httpd_resp_set_status(req, "404 Not Found");
        return httpd_resp_send(req, nullptr, 0);
    }
    bool notModified = false;
    char inm[48];
    size_t l = httpd_req_get_hdr_value_len(req, "If-None-Match");
    if (l > 0 && l < sizeof(inm) && httpd_req_get_hdr_value_str(req, "If-None-Match", inm, sizeof(inm)) == ESP_OK) {
        notModified = strcmp(inm, a->etag) == 0;
    }
    httpd_resp_set_hdr(req, "Cache-Control", "no-cache");
    httpd_resp_set_hdr(req, "ETag", a->etag);
    if (notModified) {
        httpd_resp_set_status(req, "304 Not Modified");
        return httpd_resp_send(req, nullptr, 0);
    }
    httpd_resp_set_type(req, "application/json; charset=utf-8");
    httpd_resp_set_hdr(req, "Content-Encoding", "gzip");
    httpd_resp_set_hdr(req, "X-Content-Type-Options", "nosniff");
    // Straight from the static const array in flash, no copy in RAM.
    return httpd_resp_send(req, (const char*)a->gz, (ssize_t)a->len);
}

